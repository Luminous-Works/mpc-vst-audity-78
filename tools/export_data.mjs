// Generates src/lumina/generated_data.hpp from the TypeScript reference emulator.
//
// The WebAudio emulator in src/ is the source of truth for wavetables, parameter
// ranges and factory patches (see docs/VST3-PORT.md). This tool turns that data
// into a C++ header so the native builds (MPC VST2, VST3) cannot drift from it.
//
//   node tools/export_data.mjs            # rewrites src/lumina/generated_data.hpp
//
// Needs Node 22.6+ (built-in TypeScript type stripping). No npm install needed.
// The .ts data files only use erasable syntax; we copy them to a temp folder with
// type-only imports marked `import type` and explicit .ts extensions, then import them.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'audity-export-'));

function stage(rel) {
  fs.mkdirSync(path.join(tmp, path.dirname(rel)), { recursive: true });
  let s = fs.readFileSync(path.join(root, 'src', rel), 'utf8');
  s = s.replace(/import\s*\{([^}]*)\}\s*from\s*'(\.\.?\/types\/synth)';/g, "import type {$1} from '$2.ts';");
  s = s.replace(/from\s*'(\.\/presets_banks_eh)';/g, "from '$1.ts';");
  fs.writeFileSync(path.join(tmp, rel), s);
}
fs.writeFileSync(path.join(tmp, 'package.json'), '{"type":"module"}');
['types/synth.ts', 'data/wavetables.ts', 'data/presets.ts', 'data/presets_banks_eh.ts'].forEach(stage);

const wt = await import(pathToFileURL(path.join(tmp, 'data/wavetables.ts')).href);
const ps = await import(pathToFileURL(path.join(tmp, 'data/presets.ts')).href);

const WAVES = wt.FACTORY_WAVETABLES;
const DESC = Object.values(wt.PARAMETER_DESCRIPTORS);
const bankA = ps.FACTORY_PRESETS.filter((p) => p.bank === 'A').sort((a, b) => a.slot - b.slot);
if (bankA.length !== 16) throw new Error(`expected 16 bank A patches, got ${bankA.length}`);

const waveIndex = (id) => {
  const i = WAVES.findIndex((w) => w.id === id);
  if (i < 0) throw new Error(`unknown wavetable id ${id}`);
  return i;
};
const f = (x) => { let s = String(Number(Number(x).toPrecision(7))); if (!/[.e]/.test(s)) s += '.0'; return s + 'f'; };
const arr = (a) => '{' + a.map(f).join(',') + '}';
const LFO = ['sine', 'triangle', 'saw', 'square', 'sampleHold'];
const VMODE = ['poly16', 'unison', 'mono'];

let o = `// GENERATED by tools/export_data.mjs from src/data/*.ts. Do not edit by hand.
// Re-run: node tools/export_data.mjs
#pragma once
#include <cstddef>

namespace audity {

constexpr int kWaveLen = 128;
constexpr int kNumWaves = ${WAVES.length};

struct WaveDef { const char* id; const char* name; float a[kWaveLen]; float b[kWaveLen]; };
// a = frame at morph 0, b = frame at morph 1 (equal to a when the source has no second frame).
static const WaveDef kWaves[kNumWaves] = {
`;
for (const w of WAVES) {
  const A = w.samples;
  const B = w.morphSamples && w.morphSamples.length === A.length ? w.morphSamples : A;
  if (A.length !== 128) throw new Error(`${w.id}: ${A.length} samples`);
  o += `  { ${JSON.stringify(w.id)}, ${JSON.stringify(w.name)}, ${arr(A)}, ${arr(B)} },\n`;
}
o += `};

// Continuous parameters in reference order (ParamKey in src/types/synth.ts).
struct ParamDef { const char* id; const char* shortName; const char* label; float min, max, def; bool logCurve; const char* unit; };
constexpr int kNumContinuous = ${DESC.length};
static const ParamDef kParams[kNumContinuous] = {
`;
for (const d of DESC) {
  o += `  { ${JSON.stringify(d.key)}, ${JSON.stringify(d.shortLabel)}, ${JSON.stringify(d.label)}, ${f(d.min)}, ${f(d.max)}, ${f(d.defaultValue)}, ${d.curve === 'log' ? 'true' : 'false'}, ${JSON.stringify(d.unit)} },\n`;
}
o += `};

// Discrete per-patch state (not in ParamKey). Order is the order of the native parameters after the continuous ones.
struct Discrete { int voiceMode, vco1Wave, vco1Oct, vco2Wave, vco2Oct, vco2Sync, lfoShape; };

// Factory bank A, slot order. Continuous values are plain units, in kParams order.
struct Program { const char* name; Discrete d; float v[kNumContinuous]; };
constexpr int kNumPrograms = ${bankA.length};
static const Program kPrograms[kNumPrograms] = {
`;
for (const p of bankA) {
  const d = [VMODE.indexOf(p.voiceMode), waveIndex(p.vco1WaveId), p.vco1Octave, waveIndex(p.vco2WaveId), p.vco2Octave, p.vco2Sync ? 1 : 0, LFO.indexOf(p.lfoShape)];
  if (d[0] < 0 || d[6] < 0) throw new Error(`${p.id}: bad enum`);
  o += `  { ${JSON.stringify(p.name)}, {${d.join(',')}}, ${arr(DESC.map((x) => p[x.key]))} },\n`;
}
o += `};

} // namespace audity
`;

const out = path.join(root, 'src', 'lumina', 'generated_data.hpp');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, o);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`wrote ${path.relative(root, out)}: ${WAVES.length} wavetables, ${DESC.length} continuous params, ${bankA.length} programs (${o.length} bytes)`);
