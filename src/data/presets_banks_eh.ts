function makeSeq(notes: number[], gates?: boolean[], accents?: boolean[]): SequencerStep[] {
  return notes.map((n, i) => ({
    noteOffset: n,
    gate: gates ? gates[i] : true,
    accent: accents ? accents[i] : i % 4 === 0,
    morphOffset: Number((((i * 3) % 10) / 10).toFixed(2)),
  }));
}

